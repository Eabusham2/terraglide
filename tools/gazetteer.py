#!/usr/bin/env python3
"""
Builds src/geo/gazetteerData.js: every feature the IAU has named on each world
the game can travel to, from the USGS Gazetteer of Planetary Nomenclature.

The gazetteer publishes one KMZ of feature centre points per body:
  https://asc-planetarynames-data.s3.us-west-2.amazonaws.com/<BODY>_nomenclature_center_pts.kmz
Each placemark carries the name, its centre in planetocentric east-positive
degrees, its diameter in kilometres and its feature type. Every one of them is
kept except the Moon's seven thousand satellite craters ("Copernicus A",
"Copernicus B"...), which are lettered after their parent rather than named.

    python3 tools/gazetteer.py [folder of downloaded .kmz files]

With no folder it downloads them. Public domain (USGS); the IAU names are the
IAU's.
"""
import json
import os
import re
import sys
import urllib.request
import zipfile
from io import BytesIO

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'geo', 'gazetteerData.js')
SOURCE = 'https://asc-planetarynames-data.s3.us-west-2.amazonaws.com/{}_nomenclature_center_pts.kmz'
BODIES = ['moon', 'mars', 'mercury', 'venus', 'ceres', 'vesta', 'io', 'europa',
          'ganymede', 'callisto', 'titan', 'enceladus', 'pluto', 'charon']


def load(body, folder):
    name = body.upper()
    if folder:
        with open(os.path.join(folder, f'{name}.kmz'), 'rb') as f:
            data = f.read()
    else:
        with urllib.request.urlopen(SOURCE.format(name)) as response:
            data = response.read()
    archive = zipfile.ZipFile(BytesIO(data))
    kml = next(n for n in archive.namelist() if n.endswith('.kml'))
    return archive.read(kml).decode('utf8')


def singular(kind):
    # "Crater, craters" -> "crater"; "Astronaut-named features" -> "".
    word = kind.split(',')[0].strip().lower()
    return '' if 'astronaut' in word or 'albedo' in word else word


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else None
    tables = {}
    kinds = {}
    for body in BODIES:
        rows = []
        for placemark in re.findall(r'<Placemark.*?</Placemark>', load(body, folder), re.S):
            fields = dict(re.findall(r'<SimpleData name="(\w+)">(.*?)</SimpleData>', placemark, re.S))
            point = re.search(r'<coordinates>([-\d.]+),([-\d.]+)', placemark)
            if not point or fields.get('code') == 'SF':
                continue
            if fields.get('approval') != 'Adopted by IAU':
                continue
            # Every name has to draw in any font (the self-test holds them to
            # Latin-1): a typographic apostrophe becomes a plain one.
            name = (fields.get('clean_name') or '').replace('\u2019', "'").replace('\u2018', "'")
            if not name or ';' in name or '|' in name:
                continue
            lon = float(point.group(1))
            lat = float(point.group(2))
            diameter = float(fields.get('diameter') or 0)
            code = fields.get('code') or ''
            kinds[code] = singular(fields.get('type') or '')
            # Three decimals for anything smaller than a few kilometres (the
            # astronaut-named boulders and craters at the landing sites), two
            # for the rest: a hundredth of a degree is a few hundred metres.
            places = 3 if diameter < 5 else 2
            rows.append((diameter, f'{name};{lat:.{places}f};{lon:.{places}f};{diameter:.3g};{code}'))
        rows.sort(key=lambda r: -r[0])
        tables[body] = '|'.join(r[1] for r in rows)
    with open(OUT, 'w', encoding='utf8') as f:
        f.write('/**\n')
        f.write(' * Every IAU-named feature on each world, from the USGS Gazetteer of\n')
        f.write(' * Planetary Nomenclature. Generated by tools/gazetteer.py - do not edit by\n')
        f.write(' * hand. One string per body, features largest first, separated by "|":\n')
        f.write(' * name;lat;lon;diameter in km;type code, in planetocentric east-positive\n')
        f.write(' * degrees.\n')
        f.write(' */\n')
        f.write('export const FEATURE_KINDS = ')
        f.write(json.dumps(dict(sorted(kinds.items())), ensure_ascii=True))
        f.write(';\n\nexport const FEATURES = {\n')
        for body in BODIES:
            f.write(f'  {body}: {json.dumps(tables[body], ensure_ascii=True)},\n')
        f.write('};\n')
    total = sum(t.count('|') + 1 for t in tables.values())
    print(f'{total} features, {os.path.getsize(OUT)} bytes -> {OUT}')


main()
