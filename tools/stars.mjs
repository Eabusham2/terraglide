#!/usr/bin/env node
/**
 * Builds `src/world/starCatalogue.js`: every star in the Yale Bright Star
 * Catalogue down to magnitude 5.5, packed small enough to ship inside the
 * single-file build.
 *
 * The catalogue is the fifth edition (Hoffleit and Warren, 1991), public
 * domain, read from the JSON transcription at
 *   https://github.com/brettonw/YaleBrightStarCatalog
 * which keeps each star's J2000 position, visual magnitude and the colour
 * temperature the transcription derived from its spectral type.
 *
 * Each star is six bytes — right ascension and declination as sixteen bits
 * each (a third of an arcminute, far finer than a pixel), magnitude and
 * temperature as eight — and the lot is base64 in a module, because the
 * single-file build can only carry what it can import.
 *
 *   node tools/stars.mjs [path/to/bsc5-short.json]
 */

import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'src/world/starCatalogue.js');
const SOURCE = 'https://raw.githubusercontent.com/brettonw/YaleBrightStarCatalog/master/bsc5-short.json';
const FAINTEST = 5.5;

// Shared with src/world/stars.js, which undoes exactly this.
const MAG_MIN = -1.5;
const MAG_STEP = 0.03;
const KELVIN_MIN = 2000;
const KELVIN_MAX = 40000;

async function load(path) {
  if (path) return JSON.parse(await readFile(path, 'utf8'));
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE}: ${response.status}`);
  return response.json();
}

const rows = [];
for (const star of await load(process.argv[2])) {
  const v = Number.parseFloat(star.V);
  if (!(v <= FAINTEST)) continue;
  const ra = /(\d+)h\s*(\d+)m\s*([\d.]+)s/.exec(star.RA);
  const dec = /([+-])(\d+)\D+(\d+)\D+([\d.]+)/.exec(star.Dec);
  if (!ra || !dec) continue;
  const raDeg = (Number(ra[1]) + Number(ra[2]) / 60 + Number(ra[3]) / 3600) * 15;
  let decDeg = Number(dec[2]) + Number(dec[3]) / 60 + Number(dec[4]) / 3600;
  if (dec[1] === '-') decDeg = -decDeg;
  const kelvin = Number(star.K) || 5800;
  rows.push({ raDeg, decDeg, v, kelvin });
}
// Brightest first, so a caller that wants fewer can take a prefix.
rows.sort((a, b) => a.v - b.v);

const bytes = new Uint8Array(rows.length * 6);
rows.forEach((row, i) => {
  const ra = Math.round((row.raDeg / 360) * 65535) & 0xffff;
  const dec = Math.round(((row.decDeg + 90) / 180) * 65535) & 0xffff;
  const mag = Math.max(0, Math.min(255, Math.round((row.v - MAG_MIN) / MAG_STEP)));
  const k = Math.min(KELVIN_MAX, Math.max(KELVIN_MIN, row.kelvin));
  const temp = Math.round((Math.log(k / KELVIN_MIN) / Math.log(KELVIN_MAX / KELVIN_MIN)) * 255);
  const o = i * 6;
  bytes[o] = ra >> 8;
  bytes[o + 1] = ra & 255;
  bytes[o + 2] = dec >> 8;
  bytes[o + 3] = dec & 255;
  bytes[o + 4] = mag;
  bytes[o + 5] = temp;
});

const base64 = Buffer.from(bytes).toString('base64');
const lines = base64.match(/.{1,100}/g).map((line) => `  '${line}'`).join(' +\n');
await writeFile(
  OUT,
  `/**
 * The Yale Bright Star Catalogue, fifth edition, to magnitude ${FAINTEST}:
 * ${rows.length} stars, brightest first. Generated by tools/stars.mjs — do not
 * edit by hand. Six bytes a star: right ascension and declination (J2000) as
 * big-endian sixteen-bit fractions of the circle and of the half circle,
 * magnitude in steps of ${MAG_STEP} from ${MAG_MIN}, and colour temperature on a
 * log scale from ${KELVIN_MIN} K to ${KELVIN_MAX} K.
 */
export const STAR_COUNT = ${rows.length};
export const MAG_MIN = ${MAG_MIN};
export const MAG_STEP = ${MAG_STEP};
export const KELVIN_MIN = ${KELVIN_MIN};
export const KELVIN_MAX = ${KELVIN_MAX};
export const STARS_BASE64 =
${lines};
`,
);
console.log(`${rows.length} stars, ${bytes.length} bytes -> ${OUT}`);
